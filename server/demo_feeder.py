"""Demo event feeder for live dashboard development (Lane D).

Writes a synthetic game run to logs/runs/ at a configurable rate
(default 1 event per second) so Member C can develop and verify the live
viewer and SSE streaming before the actual bot is wired up.

SAFETY / ETHICS NOTICE:
All events generated by this tool are explicitly labeled as synthetic DEMO data.
Never present demo sessions as real or verified runs.
"""

from pathlib import Path
import argparse
import random
import time

from bot.logger import RunLogger


ACTIONS = [
    {"id": "move_left", "label": "Move Left", "hint": "Shift left one lane"},
    {"id": "stay", "label": "Stay in Current Lane", "hint": "Maintain current lane"},
    {"id": "move_right", "label": "Move Right", "hint": "Shift right one lane"},
]


def run_demo_feeder(
    logs_dir: str = "logs/runs",
    steps: int = 15,
    interval: float = 1.0,
    game_id: str = "mock-demo-v1",
):
    print("=" * 64)
    print("  [DEMO FEEDER] Synthetic Live Run for Frontend UI Development")
    print("  Target Directory :", logs_dir)
    print("  Total Steps      :", steps)
    print("  Step Interval    :", f"{interval}s")
    print("  Game ID          :", game_id)
    print("  Note: All events are strictly DEMO data.")
    print("=" * 64)

    logger = RunLogger(game_id=game_id, logs_dir=logs_dir)
    session_id = logger.session_id
    print(f"\n[*] Created synthetic session: {session_id}")
    print(f"[*] Appending events to: {logger.file_path}\n")

    current_lane = 1
    score = 0

    try:
        for step in range(steps):
            obstacle_lane = random.choice([0, 1, 2])
            dist = random.randint(1, 4)

            # Laya prompt and prediction
            safe_lanes = [l for l in [0, 1, 2] if l != obstacle_lane]
            best_lane = random.choice(safe_lanes)

            # Map best lane to relative move
            if best_lane < current_lane:
                chosen_act = "move_left"
                next_lane = max(0, current_lane - 1)
            elif best_lane > current_lane:
                chosen_act = "move_right"
                next_lane = min(2, current_lane + 1)
            else:
                chosen_act = "stay"
                next_lane = current_lane

            confidence = round(random.uniform(0.72, 0.94), 2)
            other_conf = round((1.0 - confidence) / 2, 2)
            scores = {
                chosen_act: confidence,
                "move_left": other_conf if chosen_act != "move_left" else confidence,
                "stay": other_conf if chosen_act != "stay" else confidence,
                "move_right": other_conf if chosen_act != "move_right" else confidence,
            }
            # Normalize to 1.0 within float tolerance
            total_s = sum(scores.values())
            scores = {k: round(v / total_s, 4) for k, v in scores.items()}

            latency = round(random.uniform(20.0, 45.0), 1)

            # Check outcome
            collision = (next_lane == obstacle_lane and dist <= 1)
            good = not collision
            score_gain = 10 if good else -50
            score += score_gain

            state_desc = (
                f"Lane {obstacle_lane + 1} has obstacle {dist} tiles ahead. "
                f"Player is in lane {current_lane + 1}. Speed is standard."
            )

            is_last = (step == steps - 1) or collision

            event_data = {
                "step": step,
                "state": {
                    "game_id": game_id,
                    "session_id": session_id,
                    "step": step,
                    "state_text": state_desc,
                    "facts": {
                        "player_lane": current_lane,
                        "obstacle_lane": obstacle_lane,
                        "distance": dist,
                        "demo_flag": True,
                    },
                    "legal_actions": ACTIONS,
                    "score": score,
                    "done": is_last,
                },
                "laya_calls": [
                    {
                        "question_set": "perception_direct_v1",
                        "questions": [
                            {
                                "id": "q_open_lane",
                                "type": "multiple_choice",
                                "text": f"Which lane is clear of obstacles?",
                                "options": ["Lane 1", "Lane 2", "Lane 3"],
                            }
                        ],
                        "raw": {
                            "predicted_lane": f"Lane {best_lane + 1}",
                            "prob": confidence,
                            "demo": True,
                        },
                        "action_scores": scores,
                        "chosen_action": chosen_act,
                        "latency_ms": latency,
                        "accepted": True,
                        "excluded": False,
                        "legal": True,
                    }
                ],
                "validator": {
                    "retries": 0,
                    "fallback": False,
                    "rejections": [],
                },
                "final_action": chosen_act,
                "game_response": {
                    "good": good,
                    "score_before": score - score_gain,
                    "score_after": score,
                    "done": is_last,
                    "message": "DEMO: Clear trajectory" if good else "DEMO: Minor collision",
                },
                "outcome": f"DEMO step {step}: action={chosen_act}, score={score}",
            }

            logger.event(event_data)
            print(f"[{time.strftime('%H:%M:%S')}] Step {step+1:02d}/{steps:02d} | Action: {chosen_act:<10} | Conf: {confidence*100:.0f}% | Score: {score}")

            current_lane = next_lane
            if is_last:
                break

            time.sleep(interval)

    except KeyboardInterrupt:
        print("\n[!] Demo feeder paused by user.")

    finally:
        summary = logger.close({
            "final_score": score,
            "completion_status": "completed",
            "qualifying_score": None,
            "verified": "DEMO_UNVERIFIED",
        })
        print(f"\n[OK] Run closed with SHA-256: {summary['sha256'][:16]}...")
        print("[OK] Demo feeder complete.\n")


def main():
    parser = argparse.ArgumentParser(description="Synthetic Live Game Feeder for Dashboard Development")
    parser.add_argument("--logs-dir", default="logs/runs", help="Target logs directory")
    parser.add_argument("--steps", type=int, default=15, help="Number of steps to stream")
    parser.add_argument("--interval", type=float, default=1.0, help="Seconds per step")
    parser.add_argument("--game-id", default="mock-demo-v1", help="Game ID label")

    args = parser.parse_args()
    run_demo_feeder(
        logs_dir=args.logs_dir,
        steps=args.steps,
        interval=args.interval,
        game_id=args.game_id,
    )


if __name__ == "__main__":
    main()
