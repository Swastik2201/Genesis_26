"""Demo event feeder for live dashboard development (Snake & 2048).

Writes synthetic game runs to logs/runs/ at a configurable rate
(default 1 event per second) so the frontend UI and visual canvas
can stream live Snake or 2048 gameplay.

SAFETY / ETHICS NOTICE:
All events generated by this tool are explicitly labeled as synthetic DEMO data.
Never present demo sessions as real or verified runs.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import random
import time
from typing import Any

from bot.logger import RunLogger


SNAKE_ACTIONS = [
    {"id": "up", "label": "Up", "hint": "Move upward"},
    {"id": "down", "label": "Down", "hint": "Move downward"},
    {"id": "left", "label": "Left", "hint": "Move leftward"},
    {"id": "right", "label": "Right", "hint": "Move rightward"},
]


def run_demo_feeder(
    logs_dir: str = "logs/runs",
    steps: int = 20,
    interval: float = 0.8,
    game_id: str = "snake",
):
    print("=" * 64)
    print("  [DEMO FEEDER] Live Game Feeder for TopGameAI Arena")
    print("  Game ID          :", game_id)
    print("  Target Directory :", logs_dir)
    print("  Total Steps      :", steps)
    print("  Step Interval    :", f"{interval}s")
    print("=" * 64)

    logger = RunLogger(game_id=game_id, logs_dir=logs_dir)
    session_id = logger.session_id
    print(f"\n[*] Created synthetic session: {session_id}")
    print(f"[*] Appending events to: {logger.file_path}\n")

    # Snake state
    snake = [{"x": 6, "y": 6}, {"x": 5, "y": 6}, {"x": 4, "y": 6}]
    current_dir = "right"
    food = {"x": 9, "y": 3}
    food_eaten = 0
    score = 0

    try:
        for step in range(steps):
            head = snake[0]

            # Choose move toward food
            dx = food["x"] - head["x"]
            dy = food["y"] - head["y"]

            possible = []
            if dx > 0 and current_dir != "left":
                possible.append("right")
            elif dx < 0 and current_dir != "right":
                possible.append("left")
            if dy > 0 and current_dir != "up":
                possible.append("down")
            elif dy < 0 and current_dir != "down":
                possible.append("up")

            if not possible:
                possible = [d for d in ["up", "down", "left", "right"] if d != {"up": "down", "down": "up", "left": "right", "right": "left"}[current_dir]]

            chosen_act = random.choice(possible) if possible else "right"
            current_dir = chosen_act

            # Advance head
            new_head = {"x": head["x"], "y": head["y"]}
            if chosen_act == "up":
                new_head["y"] = max(0, new_head["y"] - 1)
            elif chosen_act == "down":
                new_head["y"] = min(11, new_head["y"] + 1)
            elif chosen_act == "left":
                new_head["x"] = max(0, new_head["x"] - 1)
            elif chosen_act == "right":
                new_head["x"] = min(11, new_head["x"] + 1)

            snake.insert(0, new_head)

            # Check food
            ate = (new_head["x"] == food["x"] and new_head["y"] == food["y"])
            if ate:
                food_eaten += 1
                score += 60
                food = {"x": random.randint(1, 10), "y": random.randint(1, 10)}
            else:
                snake.pop()

            confidence = round(random.uniform(0.78, 0.95), 2)
            other_conf = round((1.0 - confidence) / 3, 4)
            scores = {d["id"]: (confidence if d["id"] == chosen_act else other_conf) for d in SNAKE_ACTIONS}
            tot = sum(scores.values()) or 1.0
            scores = {k: round(v / tot, 4) for k, v in scores.items()}

            latency = round(random.uniform(25.0, 55.0), 1)
            is_last = (step == steps - 1)

            event_data = {
                "step": step,
                "state": {
                    "game_id": game_id,
                    "session_id": session_id,
                    "step": step,
                    "state_text": f"Snake head is at col {new_head['x']}, row {new_head['y']} moving {chosen_act}. Food is at col {food['x']}, row {food['y']}. Eaten: {food_eaten}/15.",
                    "facts": {
                        "snake": [{"x": s["x"], "y": s["y"]} for s in snake],
                        "food": food,
                        "direction": chosen_act,
                        "food_eaten": food_eaten,
                        "grid_size": [12, 12],
                        "body_length": len(snake),
                        "demo_flag": True,
                    },
                    "legal_actions": SNAKE_ACTIONS,
                    "score": score,
                    "done": is_last,
                },
                "laya_calls": [
                    {
                        "question_set": "game1_v1_perception",
                        "questions": [
                            {
                                "id": "safest_direction",
                                "type": "choice",
                                "text": "Which adjacent tile is completely clear of obstacles?",
                                "options": ["up", "down", "left", "right"],
                            }
                        ],
                        "raw": {
                            "predicted_direction": chosen_act,
                            "prob": confidence,
                            "demo": True,
                        },
                        "action_scores": scores,
                        "chosen_action": chosen_act,
                        "latency_ms": latency,
                        "accepted": True,
                        "excluded": False,
                        "legal": True,
                    }
                ],
                "validator": {
                    "retries": 0,
                    "fallback": False,
                    "rejections": [],
                },
                "final_action": chosen_act,
                "game_response": {
                    "good": True,
                    "score_before": score - (60 if ate else 0),
                    "score_after": score,
                    "done": is_last,
                    "message": "DEMO: Clear trajectory" if not ate else "DEMO: Food collected!",
                },
                "outcome": f"DEMO step {step}: action={chosen_act}, score={score}",
            }

            logger.event(event_data)
            print(f"[{time.strftime('%H:%M:%S')}] Step {step+1:02d}/{steps:02d} | Action: {chosen_act:<6} | Conf: {confidence*100:.0f}% | Score: {score} | Food: {food_eaten}/15")

            if is_last:
                break
            time.sleep(interval)

    except KeyboardInterrupt:
        print("\n[!] Demo feeder paused by user.")

    finally:
        summary = logger.close({
            "final_score": score,
            "completion_status": "completed",
            "qualifying_score": 1000 if food_eaten >= 15 else None,
            "verified": "DEMO_UNVERIFIED",
        })
        print(f"\n[OK] Run closed with SHA-256: {summary['sha256'][:16]}...")
        print("[OK] Demo feeder complete.\n")


def main():
    parser = argparse.ArgumentParser(description="Live Game Feeder for TopGameAI Arena")
    parser.add_argument("--logs-dir", default="logs/runs", help="Target logs directory")
    parser.add_argument("--steps", type=int, default=20, help="Number of steps to stream")
    parser.add_argument("--interval", type=float, default=0.8, help="Seconds per step")
    parser.add_argument("--game-id", default="snake", help="Game ID label (snake or 2048)")

    args = parser.parse_args()
    run_demo_feeder(
        logs_dir=args.logs_dir,
        steps=args.steps,
        interval=args.interval,
        game_id=args.game_id,
    )


if __name__ == "__main__":
    main()
